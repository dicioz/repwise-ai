test('PWA: manifest e service worker sotto base path, riapertura senza rete',async({page,context})=>{
 await page.goto('./');await page.getByRole('button',{name:'Esplora la demo separata'}).click()
 await page.evaluate(async()=>{await navigator.serviceWorker.ready})
 await page.waitForFunction(()=>!!navigator.serviceWorker.controller)
 const manifest=await page.request.get('manifest.webmanifest');expect(manifest.ok()).toBe(true);expect((await manifest.json()).scope).toBe('/repwise-ai/')
 await context.setOffline(true);await page.reload()
 await expect(page.getByRole('heading',{name:'Pronto a fare progressi?'})).toBeVisible()
})

