 const state=emptyState(),routine={id:uid(),name:'A · Confronto',archived:false,exercises:[newExercise('Squat')]};state.routines=[routine]
 for(const date of ['2026-10-23T10:00:00Z','2026-10-26T10:00:00Z']){const s=startSession(routine,[]);s.started=date;s.finished=date;s.status='completed';s.exercises[0].sets.forEach(x=>{x.weight=85;x.rpe=8;x.reps=6;x.done=true});state.sessions.push(s)}
